"""mkembfonts.py OUT [CLASS=FILE ...] - the table of the fonts built into
the engine (src/include/bgi/embfonts.h), from the Makefile's EMBED_FONTS.

CLASS is gothic (or sans), mincho (or serif), pgothic or pmincho (the
proportional ones); FILE a TrueType or OpenType font or collection.  Each font becomes a string literal (the printable
characters as they are, the rest as octal escapes), which compilers read far
faster than a list of numbers.  OUT is written only when it changes, so the
engine is not linked again on every build.
"""
import os
import sys

CLASSES = {"gothic": 0, "sans": 0, "mincho": 1, "serif": 1, "pgothic": 2, "pmincho": 3}
MAGICS = (b"\x00\x01\x00\x00", b"OTTO", b"true", b"ttcf")


def literal(data):
    """the bytes as C string literal lines of 64 bytes each"""
    lines = []
    for i in range(0, len(data), 64):
        parts = []
        for b in data[i:i + 64]:
            c = chr(b)
            if 0x20 <= b < 0x7f and c not in '"\\?':
                parts.append(c)
            else:
                parts.append("\\%03o" % b)
        lines.append('\t"' + "".join(parts) + '"')
    return "\n".join(lines) if lines else '\t""'


def main(argv):
    if len(argv) < 2:
        sys.exit("usage: mkembfonts.py OUT [CLASS=FILE ...]")
    out = argv[1]
    fonts = []
    for spec in argv[2:]:
        cls, sep, path = spec.partition("=")
        if not sep or cls.lower() not in CLASSES:
            sys.exit("mkembfonts.py: %s: give CLASS=FILE, CLASS one of %s" % (spec, ", ".join(sorted(CLASSES))))
        try:
            with open(path, "rb") as f:
                data = f.read()
        except OSError as e:
            sys.exit("mkembfonts.py: %s: %s" % (path, e.strerror))
        if data[:4] not in MAGICS:
            sys.exit("mkembfonts.py: %s: not a TrueType or OpenType font" % path)
        if len(data) >= 1 << 32:
            sys.exit("mkembfonts.py: %s: too large" % path)
        name = os.path.basename(path).encode("ascii", "replace").decode().replace("\\", "/").replace('"', "'")
        fonts.append((CLASSES[cls.lower()], name, data))
    text = ["/* generated by tools/mkembfonts.py from EMBED_FONTS: do not edit */",
            '#include "bgi/embfonts.h"', ""]
    for i, (cls, name, data) in enumerate(fonts):
        text.append("static const char kFont%d[] =\n%s;" % (i, literal(data)))
        text.append("")
    entries = ["\t{\"%s\", %d, (const uint8_t*)kFont%d, %du}," % (name, cls, i, len(data))
               for i, (cls, name, data) in enumerate(fonts)]
    text.append("const EmbeddedFont_t gEmbeddedFonts[] = {")
    text.extend(entries if entries else ["\t{\"\", 0, (const uint8_t*)\"\", 0},"])
    text.append("};")
    text.append("const int gEmbeddedFontCount = %d;" % len(fonts))
    text = "\n".join(text) + "\n"
    try:
        with open(out, "r", encoding="latin-1") as f:
            if f.read() == text:
                return
    except OSError:
        pass
    with open(out, "w", encoding="latin-1") as f:
        f.write(text)
    if fonts:
        print("  FONTS %s" % ", ".join("%s (%s, %d KB)" % (n, ("gothic", "mincho", "pgothic", "pmincho")[c], len(d) // 1024) for c, n, d in fonts))


if __name__ == "__main__":
    main(sys.argv)
